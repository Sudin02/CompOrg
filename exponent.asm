.ORIG x3000

LD R0, X
LD R1, Y

AND R2, R2, #0
ADD R2, R2, #1

ADD R1, R1, #0
BRz DONE

POWERLOOP
AND R3, R3, #0
ADD R4, R0, #0

MULTLOOP
ADD R3, R3, R2
ADD R4, R4, #-1
BRp MULTLOOP

ADD R2, R3, #0
ADD R1, R1, #-1
BRp POWERLOOP

DONE
LD R5, ADDRESS
STR R2, R5, #0

HALT

X       .FILL #2
Y       .FILL #3
ADDRESS .FILL x8000

.END